// Non-leap cumulative month offsets; Jan 1 -> ordinal 1.
const ANWAA_MONTH_STARTS = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];

function anwaaOrdinal(month, day) {
  return ANWAA_MONTH_STARTS[month - 1] + day;
}

/** Inclusive range test; handles ranges that wrap across new year. */
function anwaaInRange(month, day, range) {
  const k = month * 100 + day;
  const start = range[0][0] * 100 + range[0][1];
  const end = range[1][0] * 100 + range[1][1];
  return start <= end ? (k >= start && k <= end) : (k >= start || k <= end);
}

/** Name lookup tolerant of diacritics, alef variants and tatweel. */
function findTalea(name) {
  const target = normalizeAnwaaText(name);
  for (let i = 0; i < anwaaList.length; i++) {
    if (normalizeAnwaaText(anwaaList[i].name) === target) return anwaaList[i];
  }
  return null;
}

/**
 * Umm al-Qura -> Gregorian via Julian Day Number.
 *
 * The arithmetic-Hijri approximation is accurate to roughly +/- a day, which
 * is the tolerance needed to place a date inside a mansion or season window.
 */
function hijriToGregorian(hy, hm, hd) {
  hy = +hy; hm = +hm; hd = +hd;
  if (!(hy > 0 && hm >= 1 && hm <= 12 && hd >= 1 && hd <= 30)) return null;

  // jd = Julian day, offset 386 aligns the epoch with the tabular calendar.
  const jd = Math.floor((11 * hy + 3) / 30) + Math.floor(354 * hy) +
    Math.floor(30 * hm) - Math.floor((hm - 1) / 2) + hd + 1948440 - 386;

  // Four-step Julian day -> Gregorian civil date (Fliegel & Van Flandern).
  let l = jd + 68569;
  const n = Math.floor((4 * l) / 146097);
  l = l - Math.floor((146097 * n + 3) / 4);
  const i = Math.floor((4000 * (l + 1)) / 1461001);
  l = l - Math.floor((1461 * i) / 4) + 31;
  const j = Math.floor((80 * l) / 2447);
  const day = l - Math.floor((2447 * j) / 80);
  l = Math.floor(j / 11);
  const month = j + 2 - 12 * l;
  const year = 100 * (n - 49) + i + l;
  const d = new Date(year, month - 1, day);
  return isNaN(d.getTime()) ? null : d;
}

/** Strips diacritics and folds alef/ya variants so names compare equal. */
function normalizeAnwaaText(text) {
  return String(text == null ? '' : text)
    .replace(/[\u064B-\u0652\u0670\u0640]/g, '')
    .replace(/[\u0623\u0625\u0622\u0671]/g, '\u0627')
    .replace(/\u0649/g, '\u064A')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Full mansion records for a season, in the season's chronological order. */
function getSeasonTales(season) {
  if (!season || !season.tales) return [];
  const out = [];
  for (let i = 0; i < season.tales.length; i++) {
    const talea = findTalea(season.tales[i]);
    if (talea) out.push(talea);
  }
  return out;
}

/** Opening mansion of a season — the one shown on selection. */
function getSeasonFirstTalea(season) {
  const tales = getSeasonTales(season);
  return tales.length ? tales[0] : null;
}

/** Season containing a date, or null if it falls in no season window. */
function getSeasonOfDate(date = new Date()) {
  const month = date.getMonth() + 1;
  const day = date.getDate();
  for (let i = 0; i < anwaaSeasons.length; i++) {
    if (anwaaInRange(month, day, anwaaSeasons[i].range)) return anwaaSeasons[i];
  }
  return null;
}

/** Season a mansion belongs to, resolved through its `season` field. */
function getSeasonOfTalea(talea) {
  if (!talea || !talea.season) return null;
  const key = normalizeAnwaaText(talea.season);
  for (let i = 0; i < anwaaSeasons.length; i++) {
    if (normalizeAnwaaText(anwaaSeasons[i].key) === key) return anwaaSeasons[i];
  }
  return null;
}

/** Localised month/day, e.g. "٢٤ أغسطس". */
function formatAnwaaDate(month, day) {
  const base = new Date(Date.UTC(2025, month - 1, day));
  try {
    return new Intl.DateTimeFormat('ar', { day: 'numeric', month: 'long' }).format(base);
  } catch (err) {
    return day + '/' + month;
  }
}

/** Season span as a phrase, e.g. "من ٢٤ أغسطس إلى ١٥ أكتوبر". */
function formatSeasonRange(season) {
  if (!season || !season.range) return '';
  return 'من ' + formatAnwaaDate(season.range[0][0], season.range[0][1]) +
    ' إلى ' + formatAnwaaDate(season.range[1][0], season.range[1][1]);
}

/** Mansion rise date as a phrase, e.g. "يطلع في ٢٤ أغسطس". */
function formatTaleaDate(talea) {
  if (!talea || !talea.start) return '';
  return 'يطلع في ' + formatAnwaaDate(talea.start[0], talea.start[1]);
}