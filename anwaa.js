/**
 * Resolve the mansion in effect on a given date.
 *
 * Dates are packed into an MMDD integer (Sep 9 -> 909) so the whole
 * comparison collapses to a single numeric test, and entries are scanned
 * backwards from year-end to find the latest start <= now.
 */
function getCurrentTalea(date = new Date()) {
  const currentKey = (date.getMonth() + 1) * 100 + date.getDate();

  for (let i = anwaaList.length - 1; i >= 0; i--) {
    if (currentKey >= anwaaList[i].start[0] * 100 + anwaaList[i].start[1]) {
      return anwaaList[i];
    }
  }

  // 1-2 Jan precedes every start date, so it falls back to year-end.
  return anwaaList[anwaaList.length - 1];
}

